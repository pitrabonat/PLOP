using System.Collections.Generic;
using System.IO;
using System.Text;
using Plop.Presentation;
using UnityEditor;
using UnityEngine;

namespace Plop.CharacterTools
{
    /// <summary>
    /// Phase 11.6 art pack import. Reads the untouched delivery in Documentation/ArtPack/Phase11_6/Sprites,
    /// cleans each sprite (faint alpha noise and stray specks removed, colour bled under transparent pixels so
    /// bilinear filtering never shows a halo), recentres it on its real anchor (tile centre, fan hub, ring hole)
    /// with a whole-pixel shift (no resampling), writes it to Assets/Art/Phase11_6/&lt;group&gt;/, applies the sprite
    /// import settings, creates the Lava / Frost materials and the runtime <see cref="ArtPackAsset"/>, and writes
    /// an inspection report next to the originals. Re-running it is safe and reproducible.
    /// </summary>
    public static class ArtPackImporter
    {
        private const string SourceDir = "Documentation/ArtPack/Phase11_6/Sprites";
        private const string ReportPath = "Documentation/ArtPack/Phase11_6/IMPORT_REPORT.md";
        private const string Root = "Assets/Art/Phase11_6";
        private const string AssetPath = "Assets/Art/Resources/ArtPack/Phase11_6.asset";
        private const int FaintAlpha = 10;       // alpha below this is generation noise, not edge antialiasing
        private const int MinSpeck = 64;         // disconnected islands smaller than this are removed

        private enum Anchor { Bounds, Hub, Hole }

        private static readonly (string Name, string Group, Anchor Anchor)[] Entries =
        {
            ("Floor_Ivory", "Tiles", Anchor.Bounds),
            ("Wall_Pebble", "Tiles", Anchor.Bounds),
            ("Lava_Isolated", "Tiles", Anchor.Bounds),
            ("Frost_Isolated", "Tiles", Anchor.Bounds),
            ("Fan_Housing", "Mechanics", Anchor.Hole),
            ("Fan_Blades", "Mechanics", Anchor.Hub),
            ("Portal_Frame", "Mechanics", Anchor.Hole),
            ("Portal_Vortex", "Mechanics", Anchor.Bounds),
            ("Nest_Berry", "Nests", Anchor.Bounds),
            ("Nest_Mint", "Nests", Anchor.Bounds),
            ("Nest_Honey", "Nests", Anchor.Bounds),
            ("Nest_Lilac", "Nests", Anchor.Bounds),
            ("Plop_Berry", "Characters", Anchor.Bounds),
            ("Plop_Mint", "Characters", Anchor.Bounds),
            ("Plop_Honey", "Characters", Anchor.Bounds),
            ("Plop_Lilac", "Characters", Anchor.Bounds),
        };

        [MenuItem("PLOP/Art Pack/Import Phase 11.6 Sprites")]
        public static void Import()
        {
            var report = new StringBuilder();
            report.AppendLine("# Phase 11.6 art pack: import report");
            report.AppendLine();
            report.AppendLine("Generated by `PLOP → Art Pack → Import Phase 11.6 Sprites` (`ArtPackImporter`). Originals in `Sprites/` are untouched.");
            report.AppendLine();
            report.AppendLine("| Sprite | Group | Opaque box (px) | Anchor | Shift (px) | Faint px cleared | Specks removed | Clipped px |");
            report.AppendLine("|---|---|---|---|---|---|---|---|");

            foreach (var g in new[] { "Tiles", "Characters", "Nests", "Mechanics", "Effects", "Materials" })
                Directory.CreateDirectory(Path.Combine(Root, g));

            var written = new List<string>();
            foreach (var e in Entries)
            {
                string src = Path.Combine(SourceDir, e.Name + ".png");
                if (!File.Exists(src)) { Debug.LogError("[PLOP] Art pack: missing " + src); continue; }
                var tex = new Texture2D(2, 2, TextureFormat.RGBA32, false);
                tex.LoadImage(File.ReadAllBytes(src));
                int w = tex.width, h = tex.height;
                var px = tex.GetPixels32();
                Object.DestroyImmediate(tex);

                int faint = ClearFaint(px);
                int specks = RemoveSpecks(px, w, h);
                var anchor = FindAnchor(px, w, h, e.Anchor);
                int dx = Mathf.RoundToInt(w * 0.5f - anchor.x), dy = Mathf.RoundToInt(h * 0.5f - anchor.y);
                var moved = Shift(px, w, h, dx, dy, out int clipped);
                Bleed(moved, w, h, 4);
                var box = Bounds(moved, w, h);

                var outTex = new Texture2D(w, h, TextureFormat.RGBA32, false);
                outTex.SetPixels32(moved);
                outTex.Apply();
                string dst = $"{Root}/{e.Group}/{e.Name}.png";
                File.WriteAllBytes(dst, outTex.EncodeToPNG());
                Object.DestroyImmediate(outTex);
                written.Add(dst);
                report.AppendLine($"| {e.Name} | {e.Group} | {box.width}×{box.height} | {e.Anchor} ({anchor.x:0.0}, {h - anchor.y:0.0} from top-left) | {dx:+0;-0;0}, {-dy:+0;-0;0} | {faint} | {specks} | {clipped} |");
                if (clipped > 0) Debug.LogWarning($"[PLOP] Art pack: {e.Name} lost {clipped} opaque pixels when recentred");
            }

            AssetDatabase.Refresh();
            foreach (var path in written) ConfigureSprite(path);

            var asset = AssetDatabase.LoadAssetAtPath<ArtPackAsset>(AssetPath);
            if (asset == null)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(AssetPath));
                asset = ScriptableObject.CreateInstance<ArtPackAsset>();
                AssetDatabase.CreateAsset(asset, AssetPath);
            }
            asset.floor = Sprite("Tiles/Floor_Ivory");
            asset.pebble = Sprite("Tiles/Wall_Pebble");
            asset.lava = Sprite("Tiles/Lava_Isolated");
            asset.frost = Sprite("Tiles/Frost_Isolated");
            asset.fanHousing = Sprite("Mechanics/Fan_Housing");
            asset.fanBlades = Sprite("Mechanics/Fan_Blades");
            asset.portalFrame = Sprite("Mechanics/Portal_Frame");
            asset.portalVortex = Sprite("Mechanics/Portal_Vortex");
            asset.nests = new[] { Sprite("Nests/Nest_Berry"), Sprite("Nests/Nest_Mint"), Sprite("Nests/Nest_Honey"), Sprite("Nests/Nest_Lilac") };
            asset.lavaMaterial = MaterialFor("Lava", "PLOP/Lava", asset.lava);
            asset.frostMaterial = MaterialFor("Frost", "PLOP/Frost", asset.frost);
            EditorUtility.SetDirty(asset);
            AssetDatabase.SaveAssets();

            report.AppendLine();
            report.AppendLine("Import settings: Sprite (2D and UI), Single, pivot centre, 320 pixels per unit, alpha is transparency,");
            report.AppendLine("no mipmaps, bilinear, clamp, uncompressed RGBA32, Read/Write on (the board atlas bakes sample the pixels on the CPU).");
            report.AppendLine("Anchors: Bounds = centre of the opaque box; Hub = centroid of the fan's yellow hub; Hole = centroid of the enclosed ring hole.");
            report.AppendLine("Plop_* sprites are imported as optional candidates only; the game keeps drawing Plops with the Character Studio rig.");
            File.WriteAllText(ReportPath, report.ToString());
            Debug.Log("[PLOP] Art pack imported: " + written.Count + " sprites → " + Root);
        }

        /// <summary>Batch entry: -executeMethod Plop.CharacterTools.ArtPackImporter.ImportBatch</summary>
        public static void ImportBatch()
        {
            Import();
            EditorApplication.Exit(0);
        }

        private static Sprite Sprite(string rel) => AssetDatabase.LoadAssetAtPath<Sprite>($"{Root}/{rel}.png");

        private static Material MaterialFor(string name, string shaderName, Sprite art)
        {
            string path = $"{Root}/Materials/{name}.mat";
            var shader = Shader.Find(shaderName);
            var mat = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (mat == null)
            {
                mat = new Material(shader) { name = name };
                AssetDatabase.CreateAsset(mat, path);
            }
            else mat.shader = shader;
            mat.SetTexture("_ArtTex", art != null ? art.texture : null);
            EditorUtility.SetDirty(mat);
            return mat;
        }

        private static void ConfigureSprite(string path)
        {
            var importer = (TextureImporter)AssetImporter.GetAtPath(path);
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Single;
            importer.spritePixelsPerUnit = 320;
            importer.spritePivot = new Vector2(0.5f, 0.5f);
            var settings = new TextureImporterSettings();
            importer.ReadTextureSettings(settings);
            settings.spriteAlignment = (int)SpriteAlignment.Center;
            settings.spriteMeshType = SpriteMeshType.FullRect;
            settings.spriteExtrude = 1;
            importer.SetTextureSettings(settings);
            importer.alphaSource = TextureImporterAlphaSource.FromInput;
            importer.alphaIsTransparency = true;
            importer.mipmapEnabled = false;
            importer.isReadable = true;
            importer.sRGBTexture = true;
            importer.filterMode = FilterMode.Bilinear;
            importer.wrapMode = TextureWrapMode.Clamp;
            importer.npotScale = TextureImporterNPOTScale.None;
            importer.textureCompression = TextureImporterCompression.Uncompressed;
            foreach (var platform in new[] { "Android", "iPhone" })
            {
                var p = importer.GetPlatformTextureSettings(platform);
                p.overridden = true;
                p.format = TextureImporterFormat.RGBA32;
                p.maxTextureSize = 512;
                importer.SetPlatformTextureSettings(p);
            }
            importer.SaveAndReimport();
        }

        // ------------------------------------------------------------------ pixel passes

        private static int ClearFaint(Color32[] px)
        {
            int n = 0;
            for (int i = 0; i < px.Length; i++)
                if (px[i].a > 0 && px[i].a < FaintAlpha) { px[i] = new Color32(0, 0, 0, 0); n++; }
            return n;
        }

        private static int RemoveSpecks(Color32[] px, int w, int h)
        {
            var label = new int[px.Length];
            var stack = new Stack<int>();
            var members = new List<int>();
            int removed = 0, next = 0;
            for (int i = 0; i < px.Length; i++)
            {
                if (label[i] != 0 || px[i].a == 0) continue;
                next++;
                members.Clear();
                stack.Push(i);
                label[i] = next;
                while (stack.Count > 0)
                {
                    int j = stack.Pop();
                    members.Add(j);
                    int x = j % w, y = j / w;
                    if (x > 0) Visit(j - 1); if (x < w - 1) Visit(j + 1);
                    if (y > 0) Visit(j - w); if (y < h - 1) Visit(j + w);
                }
                if (members.Count < MinSpeck)
                    foreach (int j in members) { px[j] = new Color32(0, 0, 0, 0); removed++; }
            }
            return removed;

            void Visit(int k)
            {
                if (label[k] != 0 || px[k].a == 0) return;
                label[k] = next;
                stack.Push(k);
            }
        }

        private static Vector2 FindAnchor(Color32[] px, int w, int h, Anchor anchor)
        {
            if (anchor == Anchor.Hub)
            {
                double sx = 0, sy = 0, n = 0;
                for (int i = 0; i < px.Length; i++)
                {
                    if (px[i].a < 200) continue;
                    Color.RGBToHSV(px[i], out float hue, out float s, out float v);
                    if (hue < 0.08f || hue > 0.18f || s < 0.20f || v < 0.55f) continue;
                    sx += i % w + 0.5; sy += i / w + 0.5; n++;
                }
                if (n > 50) return new Vector2((float)(sx / n), (float)(sy / n));
            }
            if (anchor == Anchor.Hole)
            {
                // Transparent pixels not reachable from the canvas border form the ring's hole.
                var outside = new bool[px.Length];
                var stack = new Stack<int>();
                for (int x = 0; x < w; x++) { Seed(x); Seed((h - 1) * w + x); }
                for (int y = 0; y < h; y++) { Seed(y * w); Seed(y * w + w - 1); }
                while (stack.Count > 0)
                {
                    int j = stack.Pop();
                    int x = j % w, y = j / w;
                    if (x > 0) Seed(j - 1); if (x < w - 1) Seed(j + 1);
                    if (y > 0) Seed(j - w); if (y < h - 1) Seed(j + w);
                }
                double sx = 0, sy = 0, n = 0;
                for (int i = 0; i < px.Length; i++)
                    if (px[i].a < 128 && !outside[i]) { sx += i % w + 0.5; sy += i / w + 0.5; n++; }
                if (n > 50) return new Vector2((float)(sx / n), (float)(sy / n));

                void Seed(int k)
                {
                    if (outside[k] || px[k].a >= 128) return;
                    outside[k] = true;
                    stack.Push(k);
                }
            }
            var b = Bounds(px, w, h);
            return new Vector2(b.x + b.width * 0.5f, b.y + b.height * 0.5f);
        }

        private static RectInt Bounds(Color32[] px, int w, int h)
        {
            int minX = w, minY = h, maxX = -1, maxY = -1;
            for (int i = 0; i < px.Length; i++)
            {
                if (px[i].a < 128) continue;
                int x = i % w, y = i / w;
                minX = Mathf.Min(minX, x); maxX = Mathf.Max(maxX, x);
                minY = Mathf.Min(minY, y); maxY = Mathf.Max(maxY, y);
            }
            return maxX < 0 ? new RectInt() : new RectInt(minX, minY, maxX - minX + 1, maxY - minY + 1);
        }

        private static Color32[] Shift(Color32[] px, int w, int h, int dx, int dy, out int clipped)
        {
            var o = new Color32[px.Length];
            clipped = 0;
            for (int y = 0; y < h; y++)
            for (int x = 0; x < w; x++)
            {
                var c = px[y * w + x];
                if (c.a == 0) continue;
                int nx = x + dx, ny = y + dy;
                if (nx < 0 || ny < 0 || nx >= w || ny >= h) { if (c.a >= 128) clipped++; continue; }
                o[ny * w + nx] = c;
            }
            return o;
        }

        /// <summary>Gives fully transparent pixels next to the sprite the colour of their opaque neighbours.</summary>
        private static void Bleed(Color32[] px, int w, int h, int passes)
        {
            var filled = new bool[px.Length];
            for (int i = 0; i < px.Length; i++) filled[i] = px[i].a > 0;
            for (int pass = 0; pass < passes; pass++)
            {
                var add = new List<(int, Color32)>();
                for (int y = 0; y < h; y++)
                for (int x = 0; x < w; x++)
                {
                    int i = y * w + x;
                    if (filled[i]) continue;
                    int r = 0, g = 0, b = 0, n = 0;
                    for (int oy = -1; oy <= 1; oy++)
                    for (int ox = -1; ox <= 1; ox++)
                    {
                        int nx = x + ox, ny = y + oy;
                        if (nx < 0 || ny < 0 || nx >= w || ny >= h) continue;
                        int k = ny * w + nx;
                        if (!filled[k]) continue;
                        r += px[k].r; g += px[k].g; b += px[k].b; n++;
                    }
                    if (n > 0) add.Add((i, new Color32((byte)(r / n), (byte)(g / n), (byte)(b / n), 0)));
                }
                foreach (var (i, c) in add) { px[i] = c; filled[i] = true; }
            }
        }
    }
